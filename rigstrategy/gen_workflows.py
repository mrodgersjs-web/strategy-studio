import json,pathlib
methods=[m['id'] for m in json.load(open('src/strategy_studio/data/methods.json'))['methods']]
stages=["frame","diagnose","options","numbers","stress","commit","operate","visual-quality","antipattern","learn"]
O=pathlib.Path("rigstrategy/workflows")
T='''// {name}.workflow.js - compiled from skill {name} (generated by rigstrategy/gen_workflows.py)
export const meta = {{
  name: '{name}',
  description: 'Run stage {stage} of the {method} strategy method on a routed question, then adversarially verify the output with independent skeptics.',
  whenToUse: 'When strategy-studio routed a question to {method} and the run is at stage {stage}.',
  phases: [
    {{ title: 'Produce', detail: 'Read the routed worksheet and produce the {stage} output; every number cites a source or is marked UNVERIFIED.' }},
    {{ title: 'Verify', detail: 'Two zero-context skeptics try to refute the output; it survives only if a majority fail to refute.' }},
  ],
}};
const worksheet = (args && args.worksheet) || '';
const outSchema = {{ type: 'object', properties: {{ output: {{ type: 'string' }}, sources: {{ type: 'array', items: {{ type: 'string' }} }} }}, required: ['output', 'sources'] }};
const verdictSchema = {{ type: 'object', properties: {{ refuted: {{ type: 'boolean' }}, reason: {{ type: 'string' }} }}, required: ['refuted', 'reason'] }};
phase('Produce');
const result = await agent(`Strategy method: {method}. Stage: {stage}.\\nWorksheet:\\n${{worksheet}}\\nProduce the {stage} output. Cite a source for every number or mark it UNVERIFIED. Drafts only; take no outward action.`, {{ label: 'produce', phase: 'Produce', schema: outSchema }});
if (!result || !result.output) {{ return {{ workflow: '{name}', ok: false, reason: 'no-output' }}; }}
phase('Verify');
const verdicts = await parallel([0, 1].map((i) => () => agent(`You have no prior context. Try to REFUTE this {method} {stage} output: find unsupported claims, invented numbers, or logic gaps.\\n\\n${{result.output}}`, {{ label: `skeptic-${{i}}`, phase: 'Verify', schema: verdictSchema }})));
const refutes = (verdicts || []).filter((v) => v && v.refuted).length;
log(`skeptics refuting: ${{refutes}}/2`);
return {{ workflow: '{name}', ok: refutes < 2, output: result.output, sources: result.sources, refutes }};
'''
for s in stages:
  for m in methods:
    n=f"rs-{m}-{s}"; (O/f"{n}.workflow.js").write_text(T.format(name=n,stage=s,method=m))
print(len(list(O.glob("*.js"))))
